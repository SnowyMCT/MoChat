"""生成演示附件素材：一张图片 + 一个 PDF。

    .venv/Scripts/python.exe tools/build_demo_assets.py

产物（**提交进仓库**，程序运行时不联网、也不生成任何东西）：

    mchat/assets/demo/配色预览.png      960×600，画的是渐变天空 + 落日 + 远山
    mchat/assets/demo/评审材料-v3.pdf   最小合法的一页 PDF（手写字节，不引入排版库）

为什么要这两张"假素材"
----------------------
1. 打开程序就能看到图片消息 / 文件消息长什么样，不用先自己找一张图；
2. 测试与截图复核可以直接拿它们当真实附件（不写临时文件、不联网）；
3. 图片故意画成有色彩变化的（渐变 + 落日），截图里"缩略图真的画出来了"一眼可辨。

图片用 QPainter 现画（只依赖 PyQt6，和 flags 精灵图同一套思路）；PDF 按最小合法结构
逐字节拼出来并回算 xref 偏移 —— 这样不需要任何 PDF 库，产物也只有几 KB。
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from mchat.core import assets as asset_paths                        # noqa: E402

PHOTO_PATH = asset_paths.demo_path(asset_paths.DEMO_PHOTO)
REPORT_PATH = asset_paths.demo_path(asset_paths.DEMO_REPORT)

WIDTH, HEIGHT = 960, 600


# --------------------------------------------------------------------- 图片
def draw_photo(path: str) -> None:
    from PyQt6.QtCore import QPointF, QRectF, Qt
    from PyQt6.QtGui import (QColor, QFont, QImage, QLinearGradient, QPainter,
                             QPolygonF, QRadialGradient)

    image = QImage(WIDTH, HEIGHT, QImage.Format.Format_RGB32)
    painter = QPainter(image)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing, True)

    # 天空：暮色渐变（上深蓝 -> 紫 -> 橘 -> 暖黄）
    sky = QLinearGradient(0, 0, 0, HEIGHT)
    sky.setColorAt(0.00, QColor("#131C33"))
    sky.setColorAt(0.38, QColor("#5B3F6E"))
    sky.setColorAt(0.64, QColor("#C4685C"))
    sky.setColorAt(0.82, QColor("#E8A05A"))
    sky.setColorAt(1.00, QColor("#F6D08A"))
    painter.fillRect(QRectF(0, 0, WIDTH, HEIGHT), sky)

    # 星星（只在上面那片深色里）
    painter.setPen(Qt.PenStyle.NoPen)
    painter.setBrush(QColor(255, 255, 255, 190))
    for x, y, r in ((120, 62, 2.0), (268, 104, 1.4), (402, 48, 2.4), (556, 96, 1.6),
                    (688, 58, 2.0), (824, 118, 1.4), (196, 168, 1.2), (742, 176, 1.6),
                    (318, 210, 1.2), (880, 60, 1.8)):
        painter.drawEllipse(QPointF(x, y), r, r)

    # 落日 + 光晕
    sun_center = QPointF(WIDTH * 0.68, HEIGHT * 0.62)
    glow = QRadialGradient(sun_center, 260)
    glow.setColorAt(0.00, QColor(255, 226, 168, 220))
    glow.setColorAt(0.45, QColor(246, 176, 106, 90))
    glow.setColorAt(1.00, QColor(240, 150, 90, 0))
    painter.setBrush(glow)
    painter.drawEllipse(sun_center, 260, 260)
    painter.setBrush(QColor("#FFE9B8"))
    painter.drawEllipse(sun_center, 62, 62)

    # 远山三层：越远越浅（颜色 + 透明度），越靠后的越往右下压
    layers = (("#6B5A7C", 0.90), ("#4C4566", 0.94), ("#2C2A44", 1.00))
    ridge = ((0.06, 0.30), (0.20, 0.52), (0.33, 0.36), (0.46, 0.60), (0.58, 0.40),
             (0.70, 0.56), (0.82, 0.34), (0.94, 0.50))
    for index, (color, alpha) in enumerate(layers):
        tone = QColor(color)
        tone.setAlphaF(alpha)
        painter.setBrush(tone)
        polygon = [QPointF(-20, HEIGHT)]
        for x_ratio, y_ratio in ridge:
            offset = 0.0 if index == 0 else index * 0.03
            polygon.append(QPointF(x_ratio * WIDTH + index * 26,
                                   (y_ratio + offset) * HEIGHT))
        polygon.append(QPointF(WIDTH + 20, HEIGHT))
        painter.drawPolygon(QPolygonF(polygon))

    # 右下角一行小字（截图里能确认"图上真的有内容"，不是纯色块）
    painter.setPen(QColor(255, 255, 255, 205))
    painter.setFont(QFont("Microsoft YaHei UI", 26, QFont.Weight.DemiBold))
    painter.drawText(QRectF(0, HEIGHT - 92, WIDTH - 46, 60),
                     int(Qt.AlignmentFlag.AlignRight | Qt.AlignmentFlag.AlignVCenter),
                     "京张 · 沿线 18:40")
    painter.end()

    if not image.save(path, "PNG"):
        raise SystemExit(f"[!] 图片写不出来：{path}")


# ---------------------------------------------------------------------- PDF
def _pdf_bytes() -> bytes:
    """最小合法的一页 PDF（ASCII 正文 + 回算的 xref 偏移）。"""
    text = ("BT /F1 22 Tf 72 742 Td (MChat demo attachment) Tj ET\n"
            "BT /F1 12 Tf 72 706 Td (Review material v3 - a stand-in file for the"
            " file-message demo.) Tj ET\n"
            "BT /F1 12 Tf 72 686 Td (Generated by tools/build_demo_assets.py."
            " No PDF library involved.) Tj ET\n"
            "BT /F1 12 Tf 72 666 Td (Real app: this would be an uploaded file id.)"
            " Tj ET\n")
    objects = [
        "<< /Type /Catalog /Pages 2 0 R >>",
        "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        ("<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842]"
         " /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>"),
        "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        f"<< /Length {len(text)} >>\nstream\n{text}endstream",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for index, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{index} 0 obj\n{body}\nendobj\n".encode("latin-1")
    startxref = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode("latin-1")
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += f"{offset:010d} 00000 n \n".encode("latin-1")
    out += (f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n"
            f"startxref\n{startxref}\n%%EOF\n").encode("latin-1")
    return bytes(out)


def main() -> int:
    from PyQt6.QtGui import QGuiApplication

    os.makedirs(os.path.dirname(PHOTO_PATH), exist_ok=True)
    app = QGuiApplication.instance() or QGuiApplication([])      # 画图/字体需要它

    draw_photo(PHOTO_PATH)
    with open(REPORT_PATH, "wb") as handle:
        handle.write(_pdf_bytes())

    for path in (PHOTO_PATH, REPORT_PATH):
        size = os.path.getsize(path)
        print(f"  OK  {path}  {size / 1024:.1f} KB")
    print(f"\n完成：{len((PHOTO_PATH, REPORT_PATH))} 个演示素材已写入 "
          f"{asset_paths.demo_dir()}")
    del app
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
